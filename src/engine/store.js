// Minimal IndexedDB key/value store. IndexedDB (unlike storage.local) can hold
// structured-cloned non-extractable CryptoKeys, so raw key bytes never persist.
const DB = 'narada';
const STORE = 'kv';
let dbp;

function db() {
  dbp ??= new Promise((resolve, reject) => {
    const req = indexedDB.open(DB, 1);
    req.onupgradeneeded = () => req.result.createObjectStore(STORE);
    req.onsuccess = () => resolve(req.result);
    req.onerror = () => reject(req.error);
  });
  return dbp;
}

async function tx(mode, fn) {
  const d = await db();
  return new Promise((resolve, reject) => {
    const t = d.transaction(STORE, mode);
    const req = fn(t.objectStore(STORE));
    t.oncomplete = () => resolve(req?.result);
    t.onerror = () => reject(t.error);
    t.onabort = () => reject(t.error);
  });
}

export const get = (key) => tx('readonly', (s) => s.get(key));
export const set = (key, value) => tx('readwrite', (s) => s.put(value, key));
export const del = (key) => tx('readwrite', (s) => s.delete(key));

export async function listPrefix(prefix) {
  const range = IDBKeyRange.bound(prefix, prefix + '￿');
  return tx('readonly', (s) => s.getAll(range));
}
